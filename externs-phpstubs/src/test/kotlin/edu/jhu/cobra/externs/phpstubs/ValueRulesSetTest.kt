/**
 * Tests for the hand-maintained value rules set rooted at [StubResources.VALUE_RULES].
 *
 * - `value rules set loads without a vocabulary` — verifies the set names no vulnerability type or source kind
 * - `value rules set is manually verified` — verifies the set's provenance
 * - `every value rules entry is an unsigned entry asserting only the value unit` — verifies the shape rule
 * - `every value rules subject is a generated entry` — verifies existence in the generated set
 * - `no value rules unit repeats the generated unit` — verifies each unconditional unit differs from the generated one
 * - `mode-switching subjects carry a conditional entry and an unconditional one` — verifies print_r and var_export
 * - `representative units follow the PHP manual` — verifies typed results and flow sets
 * - `character bounds follow the PHP manual` — verifies the copied ports of strtr, str_replace, and substr and
 *   the `/`-free result of basename
 * - `a character bound beside the generated flows repeats them exactly` — verifies str_replace, strtr, and substr
 *   differ from the generated unit only by the bound, so a change of the generated flows fails here
 * - `a builtin whose sanitizer fact covers its result declares a value unit` — verifies every function and method with
 *   a result-covering sanitizer fact declares a returns fact, and that `hash` carries its data argument to the result
 * - `an escaper or encoder of the sanitizer facts carries its argument to the result` — verifies the flow into the
 *   result and the kept sanitizer fact of rawurlencode, the pg_escape functions and the escape methods
 * - `str position functions admit false beside the integer` — verifies the return bound of strpos, stripos, strrpos,
 *   and strripos, and that strspn and strcspn keep the integer bound
 * - `a num returns bound admits no false or null` — verifies each num rule against the reflected return type
 * - `query and exception units apply to the php-src declarations` — verifies the merged records of the query
 *   methods and the exception constructors keep their php-src extension and take the reviewed unit
 * - `SPL container writes store their value argument into the receiver` — verifies each store rule
 * - `SPL container reads return what the receiver holds` — verifies each element-returning rule
 * - `SplFixedArray fromArray returns its array argument's elements` — verifies the static factory rule
 * - `SPL subclasses reach the store rules through the declared parent` — verifies subclasses declare no rules
 * - `every SPL container has a store and a read through its lineage` — verifies coverage of the containers
 * - `SPL rules are sorted by subject` — verifies the entry order of the SPL document
 * - `SPL store rules keep the generated declaration` — verifies the merged record of `SplQueue::enqueue`
 * - `callable-taking builtins declare the flows into and out of their callback` — verifies the callback flows of
 *   `array_map`, `array_filter`, `array_reduce`, `array_walk`, `usort`, `call_user_func`, `call_user_func_array`
 *   and `register_tick_function`, and that the flows around the callback are kept
 * - `every callback port names a callable parameter` — verifies each callback port of every merged function names
 *   a declared parameter whose type admits `callable`
 */
internal class ValueRulesSetTest {
    private val rules by lazy { DocumentSetLoader.load(StubResources.opener(StubResources.VALUE_RULES)) }
    private val generated by lazy { DocumentSetLoader.load(StubResources.opener(StubResources.MODELS)) }
    private val unconditional: Map<ModelSubject, ModelEntry> by lazy {
        rules.entries.filter { it.condition == null }.associateBy { it.subject }
    }

    @Test
    fun `value rules set loads without a vocabulary`() {
        assertTrue(rules.entries.isNotEmpty())
        assertTrue(rules.vocabulary.vulnTypes.isEmpty())
        assertTrue(rules.vocabulary.sourceKinds.isEmpty())
        assertTrue(rules.policy.isEmpty())
    }

    @Test
    fun `value rules set is manually verified`() {
        assertEquals(Verification.MANUAL, assertNotNull(rules.provenance).verification)
    }

    @Test
    fun `every value rules entry is an unsigned entry asserting only the value unit`() {
        for (entry in rules.entries) {
            assertNull(entry.signature, "${entry.subject}")
            assertNotNull(entry.body.returns, "${entry.subject}")
            assertNull(entry.body.sources, "${entry.subject}")
            assertNull(entry.body.sinks, "${entry.subject}")
            assertNull(entry.body.sanitizers, "${entry.subject}")
            assertNull(entry.body.throws, "${entry.subject}")
        }
    }

    @Test
    fun `every value rules subject is a generated entry`() {
        val declared = generated.entries.map { it.subject }.toSet()
        val missing = rules.entries.map { it.subject }.filter { it !in declared }
        assertTrue(missing.isEmpty(), "Subjects absent from the generated set: $missing")
    }

    @Test
    fun `no value rules unit repeats the generated unit`() {
        val units = generated.entries.associate { it.subject to it.body.valueUnit() }
        for ((subject, entry) in unconditional) {
            assertNotEquals(units.getValue(subject), entry.body.valueUnit(), "$subject")
        }
    }

    @Test
    fun `mode-switching subjects carry a conditional entry and an unconditional one`() {
        for (name in listOf("print_r", "var_export")) {
            val branches = rules.entries.filter { it.subject == FunctionSubject(name) }
            assertEquals(2, branches.size, name)
            val conditional = branches.single { it.condition != null }
            assertEquals(ArgPattern(listOf(null, BoolVal(true))), conditional.condition)
            assertEquals(ValueUnit(ReturnKind.STR, listOf(argumentToReturn(0))), conditional.body.valueUnit())
            assertNull(branches.single { it.condition == null }.body.propagation, name)
        }
    }

    @Test
    fun `representative units follow the PHP manual`() {
        assertEquals(ValueUnit(ReturnKind.NUM, listOf(argumentToReturn(0))), unitOf("strlen"))
        assertEquals(ValueUnit(ReturnKind.STR, emptyList()), unitOf("getenv"))
        assertEquals(ValueUnit(ReturnKind.STR, listOf(argumentToReturn(0))), unitOf("strstr"))
        assertEquals(ValueUnit(ReturnKind.NUM, emptyList()), unitOf("print"))
        assertEquals(
            ValueUnit(ReturnKind.ANY, listOf(Propagation(from = Port.Argument(0), to = Port.Argument(1)))),
            unitOf("parse_str"),
        )
        assertEquals(
            ValueUnit(ReturnKind.STR, listOf(Propagation(from = Port.Receiver, to = Port.Return))),
            unconditional.getValue(MethodSubject("Exception", "getMessage")).body.valueUnit(),
        )
        assertNull(unconditional[FunctionSubject("crypt")])
        assertEquals(ValueUnit(ReturnKind.STR, listOf(argumentToReturn(0))), unitOf("str_increment"))
    }

    @Test
    fun `character bounds follow the PHP manual`() {
        val arguments = { positions: List<Int> -> positions.map(Port::Argument).toSet() }
        assertEquals(CharacterBound(of = arguments(listOf(0)), within = CharacterClass("[^/]")), unitOf("basename").characters)
        assertEquals(CharacterBound(of = arguments(listOf(0, 1, 2))), unitOf("strtr").characters)
        assertEquals(CharacterBound(of = arguments(listOf(1, 2))), unitOf("str_replace").characters)
        assertEquals(CharacterBound(of = arguments(listOf(0))), unitOf("substr").characters)
        assertNull(unitOf("strlen").characters)
    }

    @Test
    fun `a character bound beside the generated flows repeats them exactly`() {
        val units = generated.entries.associate { it.subject to it.body.valueUnit() }
        for (name in listOf("str_replace", "strtr", "substr")) {
            assertEquals(units.getValue(FunctionSubject(name)), unitOf(name).copy(characters = null), name)
        }
    }

    @Test
    fun `query and exception units apply to the php-src declarations`() {
        val queries =
            mapOf(
                "mysqli::query" to ("mysqli" to ReturnKind.ANY),
                "mysqli::multi_query" to ("mysqli" to ReturnKind.BOOL),
                "mysqli::real_query" to ("mysqli" to ReturnKind.BOOL),
                "PDO::query" to ("pdo" to ReturnKind.ANY),
                "PDO::exec" to ("pdo" to ReturnKind.ANY),
                "SQLite3::query" to ("sqlite3" to ReturnKind.ANY),
                "SQLite3::exec" to ("sqlite3" to ReturnKind.BOOL),
            )
        for ((spelling, expected) in queries) {
            val record = assertNotNull(PhpStubs.method(spelling), spelling)
            assertEquals(expected.first, record.extension, spelling)
            assertEquals(expected.second, record.returns.single { it.condition == null }.kind, spelling)
            assertEquals(listOf(Port.Argument(0) to Port.Return), record.flows.map { it.from to it.to }, spelling)
        }
        for (owner in listOf("Exception", "Error")) {
            val construct = assertNotNull(PhpStubs.method("$owner::__construct"), owner)
            assertEquals("core", construct.extension, owner)
            assertEquals(listOf(Port.Argument(0) to Port.Receiver), construct.flows.map { it.from to it.to }, owner)
            val message = assertNotNull(PhpStubs.method("$owner::getMessage"), owner)
            assertEquals(ReturnKind.STR, message.returns.single { it.condition == null }.kind, owner)
            assertEquals(listOf(Port.Receiver to Port.Return), message.flows.map { it.from to it.to }, owner)
        }
    }

    @Test
    fun `str position functions admit false beside the integer`() {
        val flows = listOf(argumentToReturn(0), argumentToReturn(1))
        for (name in listOf("strpos", "stripos", "strrpos", "strripos")) {
            assertEquals(ValueUnit(ReturnKind.ANY, flows), unitOf(name), name)
        }
        for (name in listOf("strspn", "strcspn")) {
            assertEquals(ValueUnit(ReturnKind.NUM, flows), unitOf(name), name)
        }
    }

    @Test
    fun `a num returns bound admits no false or null`() {
        val stream = assertNotNull(javaClass.getResourceAsStream("/reflection/php_8_5_11.tsv"))
        val reflected =
            stream
                .bufferedReader(Charsets.UTF_8)
                .use { reader -> reader.readLines().map { it.split('\t') } }
                .filter { it.first() == "function" }
                .associate { it[1] to it[2].split('|').toSet() }
        val violations =
            unconditional.entries
                .filter { (subject, entry) -> subject is FunctionSubject && entry.body.valueUnit()?.returns == setOf(ReturnKind.NUM) }
                .mapNotNull { (subject, _) -> (subject as FunctionSubject).let { it.name to reflected[it.name] } }
                .filter { (_, parts) -> parts != null && !setOf("int", "float").containsAll(parts) }
                .map { it.first }
        assertTrue(violations.isEmpty(), "num bounds whose reflected return type is wider: $violations")
    }

    @Test
    fun `SPL container writes store their value argument into the receiver`() {
        val stores =
            mapOf(
                "ArrayObject::__construct" to listOf(0),
                "ArrayObject::append" to listOf(0),
                "ArrayObject::exchangeArray" to listOf(0),
                "ArrayObject::offsetSet" to listOf(1),
                "ArrayIterator::__construct" to listOf(0),
                "ArrayIterator::append" to listOf(0),
                "ArrayIterator::offsetSet" to listOf(1),
                "SplDoublyLinkedList::add" to listOf(1),
                "SplDoublyLinkedList::offsetSet" to listOf(1),
                "SplDoublyLinkedList::push" to listOf(0),
                "SplDoublyLinkedList::unshift" to listOf(0),
                "SplFixedArray::offsetSet" to listOf(1),
                "SplHeap::insert" to listOf(0),
                "SplObjectStorage::addAll" to listOf(0),
                "SplObjectStorage::attach" to listOf(0, 1),
                "SplObjectStorage::offsetSet" to listOf(0, 1),
                "SplObjectStorage::setInfo" to listOf(0),
                "SplPriorityQueue::insert" to listOf(0),
                "SplQueue::enqueue" to listOf(0),
            )
        for ((spelling, positions) in stores) {
            val flows = positions.map { Propagation(from = Port.Argument(it), to = Port.Receiver) }
            assertEquals(ValueUnit(ReturnKind.ANY, flows), methodUnit(spelling), spelling)
        }
    }

    @Test
    fun `SPL container reads return what the receiver holds`() {
        val reads =
            listOf(
                "ArrayObject::getArrayCopy",
                "ArrayObject::getIterator",
                "ArrayObject::offsetGet",
                "ArrayIterator::current",
                "ArrayIterator::getArrayCopy",
                "ArrayIterator::offsetGet",
                "SplDoublyLinkedList::bottom",
                "SplDoublyLinkedList::current",
                "SplDoublyLinkedList::offsetGet",
                "SplDoublyLinkedList::pop",
                "SplDoublyLinkedList::shift",
                "SplDoublyLinkedList::top",
                "SplFixedArray::getIterator",
                "SplFixedArray::offsetGet",
                "SplFixedArray::toArray",
                "SplHeap::current",
                "SplHeap::extract",
                "SplHeap::top",
                "SplObjectStorage::current",
                "SplObjectStorage::getInfo",
                "SplObjectStorage::offsetGet",
                "SplPriorityQueue::current",
                "SplPriorityQueue::extract",
                "SplPriorityQueue::top",
                "SplQueue::dequeue",
            )
        val expected = ValueUnit(ReturnKind.ANY, listOf(Propagation(from = Port.Receiver, to = Port.Return)))
        for (spelling in reads) assertEquals(expected, methodUnit(spelling), spelling)
    }

    @Test
    fun `SplFixedArray fromArray returns its array argument's elements`() {
        assertEquals(ValueUnit(ReturnKind.ANY, listOf(argumentToReturn(0))), methodUnit("SplFixedArray::fromArray"))
    }

    @Test
    fun `SPL subclasses reach the store rules through the declared parent`() {
        val parents =
            mapOf(
                "SplStack" to "spldoublylinkedlist",
                "SplQueue" to "spldoublylinkedlist",
                "SplMinHeap" to "splheap",
                "SplMaxHeap" to "splheap",
            )
        for ((subclass, parent) in parents) {
            assertEquals(parent, PhpStubs.clazz(subclass)?.classSignature?.parent, subclass)
        }
        assertNull(PhpStubs.method("SplStack::push"))
        for (spelling in listOf("SplDoublyLinkedList::push", "SplHeap::insert")) {
            val record = assertNotNull(PhpStubs.method(spelling), spelling)
            assertTrue((Port.Argument(0) to Port.Receiver) in record.flows.map { it.from to it.to }, spelling)
        }
    }

    @Test
    fun `every SPL container has a store and a read through its lineage`() {
        val containers =
            listOf(
                "ArrayObject",
                "ArrayIterator",
                "SplDoublyLinkedList",
                "SplQueue",
                "SplStack",
                "SplFixedArray",
                "SplPriorityQueue",
                "SplObjectStorage",
                "SplHeap",
                "SplMinHeap",
                "SplMaxHeap",
            )
        for (container in containers) {
            val flows = lineage(container).flatMap { owner -> methodsOf(owner).flatMap { it.flows } }
            assertTrue(flows.any { it.from is Port.Argument && it.to == Port.Receiver }, "$container store")
            assertTrue(flows.any { it.from == Port.Receiver && it.to == Port.Return }, "$container read")
        }
    }

    @Test
    fun `SPL rules are sorted by subject`() {
        val stream = assertNotNull(StubResources.opener(StubResources.VALUE_RULES).open("spl.yaml"))
        val subjects = stream.bufferedReader().use { it.readLines() }.filter { it.contains("subject:") }
        assertEquals(subjects.sorted(), subjects)
    }

    @Test
    fun `SPL store rules keep the generated declaration`() {
        val record = assertNotNull(PhpStubs.method("SplQueue::enqueue"))
        assertEquals(listOf(Port.Argument(0) to Port.Receiver), record.flows.map { it.from to it.to })
        assertEquals("spl", record.extension)
    }

    @Test
    fun `callable-taking builtins declare the flows into and out of their callback`() {
        val callbackFlows =
            mapOf(
                "array_map" to
                    listOf(
                        flow(Port.Argument(1), Port.CallbackParameter(0, 0)),
                        flow(Port.CallbackReturn(0), Port.Return),
                    ),
                "array_filter" to
                    listOf(
                        flow(Port.Argument(0), Port.CallbackParameter(1, 0)),
                        flow(Port.Argument(0), Port.CallbackParameter(1, 1)),
                    ),
                "array_reduce" to
                    listOf(
                        flow(Port.Argument(2), Port.CallbackParameter(1, 0)),
                        flow(Port.CallbackReturn(1), Port.CallbackParameter(1, 0)),
                        flow(Port.Argument(0), Port.CallbackParameter(1, 1)),
                        flow(Port.CallbackReturn(1), Port.Return),
                    ),
                "array_walk" to
                    listOf(
                        flow(Port.Argument(0), Port.CallbackParameter(1, 0)),
                        flow(Port.Argument(0), Port.CallbackParameter(1, 1)),
                        flow(Port.Argument(2), Port.CallbackParameter(1, 2)),
                    ),
                "usort" to
                    listOf(
                        flow(Port.Argument(0), Port.CallbackParameter(1, 0)),
                        flow(Port.Argument(0), Port.CallbackParameter(1, 1)),
                    ),
                "call_user_func" to
                    listOf(
                        flow(Port.Argument(1), Port.CallbackParameter(0, 0)),
                        flow(Port.CallbackReturn(0), Port.Return),
                    ),
                "call_user_func_array" to
                    listOf(
                        flow(Port.Argument(1), Port.CallbackParameter(0, 0)),
                        flow(Port.CallbackReturn(0), Port.Return),
                    ),
                "register_tick_function" to listOf(flow(Port.Argument(1), Port.CallbackParameter(0, 0))),
            )
        for ((name, expected) in callbackFlows) {
            val declared = assertNotNull(PhpStubs.function(name), name).flows.map { it.from to it.to }
            assertTrue(declared.containsAll(expected), "$name declares $declared")
        }
        // The flows around the callback stay until the interpreter consumes the callback ports.
        val aroundMap = assertNotNull(PhpStubs.function("array_map")).flows.map { it.from to it.to }
        assertTrue(flow(Port.Argument(1), Port.Return) in aroundMap)
    }

    @Test
    fun `every callback port names a callable parameter`() {
        for (record in PhpStubs.functions) {
            val callable = record.callableSignature ?: continue
            val positions =
                record.flows.flatMap { fact ->
                    listOfNotNull(
                        (fact.from as? Port.CallbackReturn)?.callable,
                        (fact.to as? Port.CallbackParameter)?.callable,
                    )
                }
            for (position in positions) {
                val type = callable.params.getOrNull(position)?.type
                assertTrue(type != null && type.alternatives.any { "callable" in it }, "${record.subject} argument($position)")
            }
        }
    }

    private fun flow(
        from: Port.Input,
        to: Port,
    ): Pair<Port.Input, Port> = from to to

    private fun unitOf(name: String): ValueUnit = unconditional.getValue(FunctionSubject(name)).body.valueUnit()!!

    private fun methodUnit(spelling: String): ValueUnit = unconditional.getValue(MethodSubject.parse(spelling)).body.valueUnit()!!

    private fun lineage(name: String): List<String> {
        val signature = PhpStubs.clazz(name)?.classSignature ?: return listOf(name)
        return listOf(name) + listOfNotNull(signature.parent).flatMap(::lineage)
    }

    private fun methodsOf(owner: String) = PhpStubs.methods.filter { it.subject.owner.equals(owner, ignoreCase = true) }

    private fun argumentToReturn(position: Int): Propagation = Propagation(from = Port.Argument(position), to = Port.Return)

    // A builtin with a sanitizer fact whose result holds its string argument declares the flow into the result; a
    // later decoder or a sink the sanitizer does not cover then reaches the source.
    @Test
    fun `an escaper or encoder of the sanitizer facts carries its argument to the result`() {
        val functions = mapOf(
            "rawurlencode" to 0, "pg_escape_string" to 1, "pg_escape_literal" to 1, "pg_escape_identifier" to 1,
        )
        for ((name, position) in functions) {
            val record = assertNotNull(PhpStubs.function(name), name)
            assertTrue(Port.Argument(position) in record.flows.filter { it.to == Port.Return }.map { it.from }, name)
            assertTrue(record.sanitizerFacts.isNotEmpty(), name)
        }
        for (spelling in listOf("SQLite3::escapeString", "mysqli::escape_string", "mysqli::real_escape_string")) {
            val record = assertNotNull(PhpStubs.method(spelling), spelling)
            assertEquals(listOf(Port.Argument(0)), record.flows.filter { it.to == Port.Return }.map { it.from }, spelling)
            assertTrue(record.sanitizerFacts.isNotEmpty(), spelling)
        }
    }

    // A sanitizer fact without a check covers the call's result; a call that declares no value unit has no
    // summarized result to carry that coverage.
    @Test
    fun `a builtin whose sanitizer fact covers its result declares a value unit`() {
        val covering = (PhpStubs.functions + PhpStubs.methods)
            .filter { record -> record.sanitizerFacts.any { it.check == null } }
        assertTrue(covering.isNotEmpty())
        for (record in covering) {
            assertTrue(record.returns.isNotEmpty(), "${record.subject} returns")
        }
        val hash = assertNotNull(PhpStubs.function("hash"))
        assertEquals(listOf(Port.Argument(1)), hash.flows.filter { it.to == Port.Return }.map { it.from })
    }
}
